/**
 * Product fonts: SSOT of the loaders and CSS variable names.
 *
 * DECISION: the `next/font` loaders live HERE, not in `_app.tsx`, because the
 * variable classes (`--font-schibsted` etc.) must sit on `<html>` in
 * `_document.tsx`, where palettes.css declares the --font-* roles. On a wrapper
 * div inside `_app` nothing outside it saw them: `<body>` and every portal to
 * `document.body` (modals, dialogs, overlays) rendered in the system sans. No
 * per-scope re-declaration is needed. `_app.tsx` imports this module too, so
 * Next's font manifest still preloads the WOFF2 files for the page.
 */
import {
  Schibsted_Grotesk,
  Instrument_Sans,
  Marcellus,
  Caveat,
} from 'next/font/google';

/**
 * Owner direction (2026-10-08): Schibsted Grotesk supplies headings, body copy
 * and controls. Instrument Sans stays on long-form blog reading surfaces.
 * Marcellus is reserved for the brand lockup, Caveat for handwritten accents.
 * Role assignments live in palettes.css; latin-ext includes Polish glyphs.
 */
export const schibsted = Schibsted_Grotesk({
  subsets: ['latin', 'latin-ext'],
  weight: 'variable',
  display: 'swap',
  // DECISION: the fallback faces are ours, matched to Schibsted glyph by glyph
  // per weight and system font (UI/styles/schibsted-fallback.css, generated by
  // scripts/fonts/gen-schibsted-fallback.py). Next's single Arial-400 face drew
  // 600 headings too narrow and the home headline jumped on swap (CLS).
  // Renaming either family or changing the order means regenerating that file.
  adjustFontFallback: false,
  fallback: ["'Schibsted Fallback Arial'", "'Schibsted Fallback Roboto'"],
  variable: '--font-schibsted',
});

export const instrument = Instrument_Sans({
  subsets: ['latin', 'latin-ext'],
  weight: 'variable',
  display: 'swap',
  // DECISION: no preload. Instrument Sans renders ONLY blog post bodies
  // (`--font-reading`); a preload put ~41 KB on the critical path of every
  // page. The blog body swaps in through the size-adjusted fallback (CLS ~0).
  preload: false,
  variable: '--font-instrument',
});

export const marcellus = Marcellus({
  // DECISION: latin only. Marcellus draws ONE ASCII string, the wordmark
  // `BRAND_CONFIG.name` in BrandLockup, so a latin-ext subset was preloaded on
  // every page and never used. Re-add it only if Marcellus sets diacritics.
  subsets: ['latin'],
  weight: '400',
  display: 'swap',
  variable: '--font-marcellus',
});

export const caveat = Caveat({
  // DD3-F11: latin-ext for PL diacritics (accent font shows up in fontAccent class on
  // hero headings — first impression matters).
  subsets: ['latin', 'latin-ext'],
  weight: '600',
  display: 'swap',
  // CWV 2026-07-08: Caveat NIE renderuje LCP zadnej strony statycznej (hero
  // headline uses Schibsted Grotesk through --font-heading; .fontAccent/Caveat zyje na ekranach /app za
  // auth). Preload na kazdej stronie kradl pasmo krytycznej sciezki LCP
  // (2 pliki woff2). display:swap pokrywa on-demand load w /app.
  preload: false,
  variable: '--font-caveat',
});

/**
 * Klasy ze zmiennymi fontów — jedna wartość dla `<html>` (`_document.tsx`).
 * Kolejność bez znaczenia: każda klasa deklaruje własną zmienną.
 */
export const FONT_VARIABLE_CLASSNAMES = `${schibsted.variable} ${instrument.variable} ${marcellus.variable} ${caveat.variable}`;
