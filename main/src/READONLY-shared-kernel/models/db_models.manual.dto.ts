export const mapStripeStatusToSubscriptionStatus = (
  stripeStatus: string
): SubscriptionStatus => {
  const mapping: Record<string, SubscriptionStatus> = {
    active: SubscriptionStatusValue.ACTIVE,
    canceled: SubscriptionStatusValue.CANCELED,
    incomplete: SubscriptionStatusValue.INCOMPLETE,
    incomplete_expired: SubscriptionStatusValue.INCOMPLETE_EXPIRED,
    past_due: SubscriptionStatusValue.PAST_DUE,
    trialing: SubscriptionStatusValue.TRIALING,
    unpaid: SubscriptionStatusValue.UNPAID,
    paused: SubscriptionStatusValue.PAUSED,
  };
  return mapping[stripeStatus] || SubscriptionStatusValue.CANCELED;
};

// DECISION (nie usuwaj tego komentarza):
// SCDUN-1 — payment_status mapowany NA PODSTAWIE subscription_status, nie binarnie
// isStripeSubscriptionActive ? PAID : UNPAID. Powod: Stripe traktuje PAST_DUE/UNPAID
// jako "aktywne" (dostep do appki podczas retry — STRIPE_ACTIVE_STATUSES), wiec stary
// binarny mapping ustawial PAID dla konta w dunningu i nadpisywal efemeryczny IN_PROGRESS
// ustawiony przez invoice.payment_failed w sekundy. Sweep dunning-downgrade szukajacy
// payment_status=IN_PROGRESS nigdy nie znajdowal konta -> platny plan bez placenia
// bezterminowo. Tutaj PAST_DUE/UNPAID -> IN_PROGRESS (dunning trwa), ACTIVE/TRIALING -> PAID,
// reszta (CANCELED/INCOMPLETE/INCOMPLETE_EXPIRED/PAUSED) -> UNPAID. To NIE zmienia dostepu:
// PAST_DUE nadal jest w STRIPE_ACTIVE_STATUSES (account_status=ACTIVE bez zmian).
export const mapStripeStatusToPaymentStatus = (
  subscriptionStatus: SubscriptionStatus
): PaymentStatus => {
  switch (subscriptionStatus) {
    case SubscriptionStatusValue.ACTIVE:
    case SubscriptionStatusValue.TRIALING:
      return PaymentStatusValue.PAID;
    case SubscriptionStatusValue.PAST_DUE:
    case SubscriptionStatusValue.UNPAID:
      return PaymentStatusValue.IN_PROGRESS;
    case SubscriptionStatusValue.CANCELED:
    case SubscriptionStatusValue.INCOMPLETE:
    case SubscriptionStatusValue.INCOMPLETE_EXPIRED:
    case SubscriptionStatusValue.PAUSED:
      return PaymentStatusValue.UNPAID;
    default: {
      const _exhaustive: never = subscriptionStatus;
      void _exhaustive;
      return PaymentStatusValue.UNPAID;
    }
  }
};

