// Writes tests/_reports/frontend-coverage.md from the same classifier as nf/atomic-coverage.
// The ESLint rule is the gate. This file only refreshes the human-readable census.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { classifyComponent } from './rules/atomic-coverage.mjs';

const MAIN = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ROOT = path.resolve(MAIN, '..');
const UI = path.join(MAIN, 'src/UI');
const REPORT = path.join(ROOT, 'tests/_reports/frontend-coverage.md');

function filesUnder(dir) {
  const out = [];
  const visit = abs => {
    for (const entry of readdirSync(abs, { withFileTypes: true })) {
      const next = path.join(abs, entry.name);
      if (entry.isDirectory()) {
        visit(next);
      } else if (entry.name.endsWith('.tsx')) {
        out.push(next);
      }
    }
  };
  visit(dir);
  return out.sort();
}

const missing = [];
const mismatch = [];
let checked = 0;
for (const abs of filesUnder(UI)) {
  const rel = path.relative(MAIN, abs).split(path.sep).join('/');
  const verdict = classifyComponent(rel, readFileSync(abs, 'utf8'));
  if (verdict === 'skip') {
    continue;
  }
  checked += 1;
  if (verdict === 'missing') {
    missing.push(rel);
  } else if (verdict === 'mismatch') {
    mismatch.push(rel);
  }
}

const lines = [
  '# Component layer naming report',
  '',
  'Generated by `main/eslint-rules/atomic-report.mjs` for the current checkout.',
  'The blocking check is `nf/atomic-coverage`. This file is the census, not a second rule.',
  '',
  'This check examines component file and export suffixes under `main/src/UI`.',
  'It does not measure behavior, accessibility or test coverage.',
  '',
  `- Files checked: ${checked}.`,
  `- Files with a layer suffix: ${checked - missing.length}.`,
  `- Files missing a layer suffix: ${missing.length}.`,
  `- Export names that do not match the layer: ${mismatch.length}.`,
  '',
  'Layer definitions: [component guide](../../main/src/UI/components/ATOMIC_LAYERS.md).',
];
if (missing.length > 0) {
  lines.push('', `## Missing layer suffix (${missing.length})`, '');
  for (const rel of missing) {
    lines.push(`- ${rel}`);
  }
}
if (mismatch.length > 0) {
  lines.push('', `## Export name mismatch (${mismatch.length})`, '');
  for (const rel of mismatch) {
    lines.push(`- ${rel}`);
  }
}
lines.push('');
mkdirSync(path.dirname(REPORT), { recursive: true });
writeFileSync(REPORT, lines.join('\n'));
if (missing.length > 0 || mismatch.length > 0) {
  console.error(
    `atomic-report: ${missing.length} missing suffix, ${mismatch.length} export mismatch`
  );
  process.exit(1);
}
console.log(
  `atomic-report: ${checked} component files, report tests/_reports/frontend-coverage.md`
);
