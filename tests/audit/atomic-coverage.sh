#!/usr/bin/env bash
# atomic-coverage.sh — FQC ratchet: EVERY component file in main/src/UI carries an
# atomic-design layer suffix (.atom/.molecule/.organism/.composition) on BOTH the
# filename AND the exported component name.
#
# INTENT (FQC §00.1+2 — anti-FDX-failure):
#   FDX FAZA 6 only suffixed main/src/UI/components/ (56 of ~330 = 18%); features/
#   layouts/primitives stayed undisciplined and the old ratchet (atomic-layers.sh)
#   measured only that subset → green at 18% coverage. THIS ratchet enumerates the
#   WHOLE component universe under src/UI and counts X/total. Exhaustion, not
#   sampling: any component file without a layer suffix = fail.
#
# SCOPE: src/UI/**/*.tsx that ARE components. NON-components are allowlisted by
#   name-pattern (hooks `useX`, `.config/.helpers/.utils/.formatters/.types/.context/
#   .store/.seed/.policy/.disambiguation/.events-map/.test/.playground`). `.playground.tsx`
#   files (features/dev/playground/) are dev-only variant harnesses used by the /ui
#   skill — scratch demos, not shipped layered components. pages/** (routing
#   shells, default-export, filename=URL) and src/application/** are OUT of scope.
#   Explicit per-file allowlist (ALLOWLIST) requires a DECISION reason inline.
#
# OUTPUT: tests/_reports/frontend-coverage.md (owner-visible proof: X/total + list).
set -euo pipefail
source "$(dirname "$0")/_utils.sh"

PROJECT_ROOT=$(get_project_root)
UI="$PROJECT_ROOT/main/src/UI"
REPORT="$PROJECT_ROOT/tests/_reports/frontend-coverage.md"
VALID='atom|molecule|organism|composition'

# Name-patterns that are NOT components (no layer suffix expected).
NONCOMPONENT_RE='\.(config|helper|helpers|utils|formatters|disambiguation|context|store|seed|policy|types|test|events-map|playground)\.tsx$|(^|/)use[A-Z][A-Za-z0-9]*\.tsx$'

# Explicit allowlist (relative to main/) — each entry needs a DECISION reason.
ALLOWLIST=(
  # DECISION (FQC FAZA 1): pliki .tsx które NIE eksportują publicznego komponentu
  # warstwowego — section-config buildery, helpery, czyste dane, internal-render.
  "src/UI/components/AppDrawer/appDrawerSections.tsx"        # getX Sections() — section-config buildery (zwracają dane, nie JSX-komponent)
  "src/UI/components/AppDrawer/appDrawerSections.admin.tsx"  # getAdminSections/getGuestSections — jw.
  "src/UI/components/Button/buttonCore.tsx"                  # Button internal: buttonClassName helper + ButtonInner (render-only, konsumowany przez Button.atom + LinkButton.atom w tym samym folderze)
  "src/UI/features/account/UserActivityPage.events.tsx"     # resolveEventVisual/categoryLabel — event-visual mapper helpers (nie komponenty)
  "src/UI/features/static/GetAppPageFeatures.tsx"           # FEATURES/GET_APP_FAQ — czyste dane (const), zero komponentów
)

print_boxed_header "ATOMIC COVERAGE (FQC — whole src/UI universe)" "🧬"

is_allowlisted() {
  local rel="$1"
  for a in "${ALLOWLIST[@]}"; do [[ "$rel" == "$a" ]] && return 0; done
  return 1
}

suffixed=0
unsuffixed=0
namemismatch=0
UNSUFFIXED_FILES=()
MISMATCH_FILES=()

while IFS= read -r -d '' file; do
  rel="${file#"$PROJECT_ROOT"/main/}"
  base="$(basename "$file")"

  # Skip non-component name-patterns + ATOMIC_LAYERS.md + explicit allowlist.
  [[ "$base" == *.md ]] && continue
  if grep -qE "$NONCOMPONENT_RE" <<<"$base"; then continue; fi
  if is_allowlisted "$rel"; then continue; fi

  if grep -qE "\.(${VALID})\.tsx$" <<<"$base"; then
    suffixed=$((suffixed + 1))
    # Name-check: the file's layer must appear as a PascalCase suffix on >=1 export.
    layer="$(echo "$base" | sed -E "s/.*\.(${VALID})\.tsx$/\1/")"
    Cap="$(echo "${layer:0:1}" | tr '[:lower:]' '[:upper:]')${layer:1}"
    if ! grep -qE "(export (const|function|class) [A-Za-z0-9]*${Cap}\b)|(export \{[^}]*[A-Za-z0-9]+${Cap}\b)|(export \{ default as [A-Za-z0-9]*${Cap}\b)" "$file"; then
      namemismatch=$((namemismatch + 1))
      MISMATCH_FILES+=("$rel (plik=.${layer}, brak eksportu *${Cap})")
    fi
  else
    unsuffixed=$((unsuffixed + 1))
    UNSUFFIXED_FILES+=("$rel")
  fi
done < <(find "$UI" -name '*.tsx' -print0)

total=$((suffixed + unsuffixed))

# Owner-visible report.
mkdir -p "$(dirname "$REPORT")"
{
  echo "# Frontend Atomic Coverage — FQC"
  echo ""
  echo "> Auto-generated by \`tests/audit/atomic-coverage.sh\`. Owner-visible proof of completeness."
  echo ""
  echo "| Metryka | Wartość |"
  echo "|---|---|"
  echo "| Component-files w src/UI | $total |"
  echo "| Z sufiksem warstwy (plik) | $suffixed |"
  echo "| BEZ sufiksu (FAZA 1 target) | $unsuffixed |"
  echo "| Sufiks-pliku bez pasującej nazwy-eksportu | $namemismatch |"
  echo "| **Pokrycie** | **$suffixed / $total** |"
  if [[ ${#UNSUFFIXED_FILES[@]} -gt 0 ]]; then
    echo ""
    echo "## Bez sufiksu warstwy ($unsuffixed)"
    printf '%s\n' "${UNSUFFIXED_FILES[@]:-}" | sort | sed 's/^/- /'
  fi
  if [[ ${#MISMATCH_FILES[@]} -gt 0 ]]; then
    echo ""
    echo "## Sufiks-pliku bez pasującej nazwy-eksportu ($namemismatch)"
    printf '%s\n' "${MISMATCH_FILES[@]:-}" | sort | sed 's/^/- /'
  fi
} > "$REPORT"

print_info "Pokrycie: $suffixed/$total component-files z sufiksem warstwy (raport: tests/_reports/frontend-coverage.md)"

if [[ $unsuffixed -gt 0 || $namemismatch -gt 0 ]]; then
  print_error "atomic-coverage: $unsuffixed bez sufiksu pliku + $namemismatch z niezgodną nazwą-eksportu."
  exit 1
fi

print_success "atomic-coverage: 100% — wszystkie $total component-files src/UI mają sufiks warstwy (plik+nazwa)."
exit 0
