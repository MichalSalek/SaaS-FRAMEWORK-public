import type { EVENTS_ALL_TYPE } from '@kernel/domain/commands-and-queries/cqrs.types';
import type { IDType } from '@kernel/application/application.types';
import type {
  EventLog,
  EventLogType,
} from '@kernel/models/db_models.generated.dto';
import type { EventLogWithoutAutogenerated } from '@kernel/models/db_models.manual.dto';
import {
  narrowEventLog,
  narrowUserActivityLogRecord,
} from '@kernel/models/type_narrowing';
import type { UserActivityLogRecord } from '@kernel/models/event-log/event_log.dto';
import { USER_FACING_ACTIVITY_EVENTS } from '@kernel/domain/event-log/event_log.config';
import { isValidCursorFormat } from '@kernel/policies/validation/validation.utils';
import type { Prisma } from '../../prisma/js-client';
import { DB_CLIENT } from '@app/db/db.client';
import { reportIssueBackend } from '@app/debugger/error-handler';
import { MAX_EVENT_LOG_PAGE_SIZE } from './event-log.config';

export type PushEventLogToDB = {
  eventName: EVENTS_ALL_TYPE;
  meta: Partial<EventLogWithoutAutogenerated> & {
    impersonated_by_admin_id?: IDType;
  };
  eventLogType?: EventLogType;
  eventPayloadToStringify?: Record<string, unknown>;
  tx?: Prisma.TransactionClient;
};

export const writeRawEventLog_IO = async (
  props: PushEventLogToDB
): Promise<EventLog | undefined> => {
  const { eventName, meta, eventLogType, eventPayloadToStringify, tx } = props;
  if (!eventLogType) {
    return undefined;
  }
  if (
    meta?.created_by_user_id === undefined ||
    meta?.created_by_user_id === null
  ) {
    reportIssueBackend({
      namespace: 'writeRawEventLog_IO',
      message: 'missing meta.created_by_user_id; skipping event log write',
      payload: { eventName, eventLogType },
      mode: 'error',
    });
    return undefined;
  }

  // SYSTEM EVENTS (created_by_user_id = 0): Skip event log write
  // System user doesn't exist in DB, can't create foreign key relation
  if (meta.created_by_user_id === '0' || meta.created_by_user_id === '') {
    reportIssueBackend({
      namespace: 'writeRawEventLog_IO',
      message:
        'System event (created_by_user_id = 0); skipping event log write',
      payload: { eventName, eventLogType },
      mode: 'info',
    });
    return undefined;
  }

  const enrichedPayload = {
    ...eventPayloadToStringify,
    ...(meta.impersonated_by_admin_id
      ? { impersonated_by_admin_id: meta.impersonated_by_admin_id }
      : {}),
  };

  const db = tx ?? DB_CLIENT.use;

  try {
    const dbResult = await db.eventLog.create({
      data: {
        event: eventName,
        event_type: eventLogType,
        event_payload: enrichedPayload ?? null,
        location: meta.location ?? null,
        language: meta.language ?? null,
        user_agent: meta.user_agent ?? null,
        client_ip: meta.client_ip ?? null,
        created_by_user_id: meta.created_by_user_id,
      },
    });

    return narrowEventLog(dbResult, 'writeRawEventLog_IO') ?? undefined;
  } catch (error) {
    reportIssueBackend({
      namespace: 'writeRawEventLog_IO_FAILED',
      message: 'Event log DB write failed',
      payload: error,
      mode: 'error',
    });
    // DECISION (nie usuwaj tego komentarza) — BUG-A tx-aware (BDX W3.0):
    // Gdy wywołane z `tx` (wewnątrz `$transaction`, np. webhooki Stripe:
    // plan-status-update / invoice / charge-dispute), błąd zapisu audytu MUSI
    // propagować, by transakcja zrobiła rollback. Połknięcie (return undefined)
    // commitowałoby mutację konta BEZ wiersza audytu finansowego + `processed=true`
    // → event nigdy nie retryuje (cicha utrata audytu). Bez `tx` (fire-and-forget
    // poza transakcją) swallow zostaje — pojedynczy log nie może wywalić requestu.
    // Wzór: subscription-update.utils.ts (tx-aware rethrow).
    if (tx) {
      throw error;
    }
    return undefined;
  }
};

// DECISION (nie usuwaj tego komentarza):
// Format-gate cursora cuid (`isValidCursorFormat` w @kernel validation.utils — SSOT
// dla obu call-sites; pelne uzasadnienie input-robustness + istnienia-PK oracle tam).
// Tu, ponad ten kontrakt: operacja zwraca zwykly ksztalt paginacji (NIE OperationResult),
// a HTTP handler nalezy do innego klastra — nie mozemy stad zwrocic 400 bez zmiany
// kontraktu i edycji handlera. Graceful-degradation (malformowany/cudzy cursor =>
// pierwsza strona) jest poprawnym, kompletnym fixem: zaden bit istnienia nie wycieka i
// klient z popsutym kursorem dostaje uzyteczna pierwsza strone zamiast bledu.

export const getEventLogsByUser_IO = async (
  userID?: IDType | null,
  eventLogType?: EventLogType,
  pagination?: { cursor?: string | undefined; take?: number | undefined },
  options?: {
    // Whitelist-filter (kernel USER_FACING_ACTIVITY_EVENTS): tylko eventy
    // zrozumiałe dla usera. Techniczne/webhook eventy zostają w logu (audit
    // trail), ale nie wychodzą na user-facing listę aktywności.
    userFacingOnly?: boolean;
  }
): Promise<{ records: UserActivityLogRecord[]; nextCursor: string | null }> => {
  if (!userID) {
    reportIssueBackend({
      namespace: 'getEventLogs_IO',
      message: 'no userID.',
      payload: eventLogType,
      mode: 'error',
    });
    return { records: [], nextCursor: null };
  }

  const cursor = pagination?.cursor;
  const takeRaw = pagination?.take ?? 50;
  const effectiveTake = Math.trunc(
    Math.min(Math.max(takeRaw, 1), MAX_EVENT_LOG_PAGE_SIZE)
  );

  // DECISION (nie usuwaj tego komentarza):
  // Existence-oracle hardening. Prisma `cursor` kotwiczy wiersz po PK PONAD CALA
  // tabela ZANIM zaaplikuje `where: { created_by_user_id }` — `where` filtruje tylko
  // zbior wynikowy, nie istnienie kotwicy. Skutek: cudze (event_log_id ofiary) vs
  // sfabrykowane (nieistniejace) cursory daja rozny wynik => 1-bit oracle "czy ten
  // event_log_id istnieje gdziekolwiek". Fix: uzyj cursora TYLKO gdy (a) ma poprawny
  // format i (b) kotwica nalezy do wolajacego (composite WHERE event_log_id +
  // created_by_user_id). W przeciwnym razie ignoruj cursor i serwuj pierwsza strone —
  // wtedy cursor-ofiary == cursor-fake == cursor-wlasny-odfiltrowany (nieodroznialne).
  // Koszt: 1 dodatkowy indexed PK lookup tylko gdy cursor jest podany — akceptowalny.
  let anchorCursor: string | undefined = undefined;
  if (cursor && isValidCursorFormat(cursor)) {
    const owns = await DB_CLIENT.use.eventLog.findFirst({
      where: { event_log_id: cursor, created_by_user_id: userID },
      select: { event_log_id: true },
    });
    if (owns) {
      anchorCursor = cursor;
    }
  }

  const dbResults = await DB_CLIENT.use.eventLog.findMany({
    where: {
      created_by_user_id: userID,
      ...(eventLogType ? { event_type: eventLogType } : {}),
      ...(options?.userFacingOnly === true
        ? { event: { in: [...USER_FACING_ACTIVITY_EVENTS] } }
        : {}),
    },
    select: {
      event_log_id: true,
      event: true,
      event_type: true,
      created_at: true,
    },
    orderBy: [{ created_at: 'desc' }, { event_log_id: 'desc' }],
    take: effectiveTake + 1,
    ...(anchorCursor
      ? { cursor: { event_log_id: anchorCursor }, skip: 1 }
      : {}),
  });

  const hasMore = dbResults.length > effectiveTake;
  const pageItems = hasMore ? dbResults.slice(0, effectiveTake) : dbResults;
  const nextCursor =
    hasMore && pageItems.length > 0
      ? (pageItems[pageItems.length - 1]?.event_log_id ?? null)
      : null;

  const records = pageItems.reduce<UserActivityLogRecord[]>((acc, e) => {
    const narrowed = narrowUserActivityLogRecord(e, 'getEventLogsByUser_IO');
    if (narrowed) {
      acc.push(narrowed);
    }
    return acc;
  }, []);

  return { records, nextCursor };
};
