// DECISION: SafeSession is Session without `token` and `userId`, the contract for every response that
// returns a session shape (GET_CURRENT, BECOME_USER, SWITCH_BACK_BECOME_USER, DEV_LOGIN, GET_ALL). The
// bearer token lives only in one device's Authorization header and the DB row, never in a response
// body; `userId` duplicates `currentUser.id`. Reference stripping pattern:
// web-1/src/pages/api/v1/session/get-current/index.ts (destructure plus spread).
export type SafeSession = Omit<Session, 'token' | 'userId'>;

