#!/bin/bash
# scripts/deploy/_pm2-remote.sh
# Wspoldzielony fragment zarzadzania PM2 do zdalnego wykonania przez SSH.
# Source lokalnie, wywolaj pm2_remote_block() po fragment komend do osadzenia w SSH heredoc.
#
# DELETE+START (nie reload/restart): atomowy deploy przepina symlink current
# na nowy release, ale `pm2 reload`/`restart` na ISTNIEJACYM procesie REUZYWA
# zapietej absolutnej sciezki STAREGO release (incydent 2026-06-25: pm2 serwowal
# stary build mimo przepiecia symlinku; dodatkowo `reload --update-env` z bledym
# PORT dawal EPERM). delete + start z biezacego cwd (current) GWARANTUJE
# uruchomienie NOWEGO release na wlasciwym, zarezerwowanym porcie.
#
# Usage (cwd na serwerze MUSI byc katalogiem release, np. current):
#   source "${SCRIPT_DIR}/_pm2-remote.sh"
#   PM2_BLOCK=$(pm2_remote_block "frontend-nailfolio.app" "0000" "nailfolio.app" "/path/on/server/bin/node")
#   ssh host "cd .../current && ${PM2_BLOCK}"

pm2_remote_block() {
  local pm2_name="$1"
  local port="$2"                                   # zarezerwowany port hostingu (WYMAGANY)
  local domain="$3"
  local node_interp="${4:-/path/on/server/bin/node}"

  # Heredoc niecytowany — $pm2_name/$port/$domain/$node_interp ekspandowane LOKALNIE.
  # \$ daje literalny $ do ewaluacji na serwerze.
  cat << PMEOF
  # PM2 (generated by _pm2-remote.sh) — delete+start na NOWY release
  PM2_NAME="${pm2_name}"
  PM2_PORT="${port}"
  echo "[REMOTE] (re)start \${PM2_NAME} na porcie \${PM2_PORT} z \$(pwd)"
  pm2 delete "\${PM2_NAME}" >/dev/null 2>&1 || true
  PORT=\${PM2_PORT} pm2 start server.js --name "\${PM2_NAME}" --interpreter "${node_interp}" --time
  pm2 save
  # Persistence: @reboot pm2 resurrect zyje w SYSTEMOWYM crontab. Panel hostingu NIE ma
  # harmonogramu zadan na tym serwerze (zweryfikowane 2026-06) — sprawdzamy crontab.
  crontab -l 2>/dev/null | grep -q 'pm2 resurrect' \
    && echo "[REMOTE] Persistence (crontab @reboot resurrect) OK." \
    || echo "[REMOTE] WARN: brak '@reboot pm2 resurrect' w crontab — dodaj: (crontab -l 2>/dev/null; echo '@reboot pm2 resurrect') | crontab -"
  # Odswiezenie proxy hostingu (best-effort; `hosting-cli` = placeholder CLI panelu; niektore typy proxy nie wspieraja restartu).
  hosting-cli www restart ${domain} >/dev/null 2>&1 || echo "[REMOTE] (info) restart proxy pominiety (typ proxy nie wspiera — OK)"
PMEOF
}
